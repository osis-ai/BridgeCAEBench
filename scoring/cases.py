"""Case files (datasets/<line>/<id>.yaml) and the projects they describe.

A project is ``empty``, ``template:<name>`` (a skill template), or ``overlay:<dir>``: the ``base`` template
with the files under ``datasets/<line>/<id>/<dir>/`` laid over it (same relative paths, e.g. prep/_8_loadcase.py)
and the paths in ``<dir>.delete`` (one per line) removed. Overlays keep a case reviewable as plain files.
"""

from __future__ import annotations

import shutil
from functools import lru_cache
from pathlib import Path
from typing import Any

import yaml

DATASETS = Path(__file__).resolve().parents[1] / "datasets"
STATUSES = ("draft", "verified", "frozen")
REQUIRED = ("id", "line", "bridge", "status", "version", "start", "brief", "checks")
# project: one session of ordered turns, each its own brief/checks/reference (turn k starts from turn k-1's output)
PROJECT_REQUIRED = ("id", "line", "bridge", "status", "version", "start", "turns")
TURN_REQUIRED = ("brief", "checks", "reference")


@lru_cache(maxsize=None)
def templates(skills: Path) -> dict[str, Path]:
    """Template name -> folder, across every skill in ``skills``."""
    found: dict[str, Path] = {}
    for folder in sorted(skills.glob("*/references/templates/*")):
        if (folder / "prep").is_dir():
            if folder.name in found:
                raise ValueError(f"template name {folder.name!r} is in two skills")
            found[folder.name] = folder
    return found


def load(path: Path) -> dict[str, Any]:
    case = yaml.safe_load(path.read_text(encoding="utf-8"))
    project = case.get("line") == "project"
    missing = [k for k in (PROJECT_REQUIRED if project else REQUIRED) if k not in case]
    if project:
        missing += [f"turns[{i}].{k}" for i, turn in enumerate(case.get("turns") or []) for k in TURN_REQUIRED
                    if k not in turn]
    if missing or case["id"] != path.stem or case["status"] not in STATUSES:
        raise ValueError(f"{path}: missing {missing} / id must equal file name / status in {STATUSES}")
    case["_dir"] = path.with_suffix("")  # attachments
    return case


def load_line(line: str, root: Path = DATASETS) -> list[dict[str, Any]]:
    return [load(p) for p in sorted((root / line).glob("*.yaml"))]


def materialize(case: dict[str, Any], which: str, skills: Path, dest: Path) -> Path:
    """Write the ``start`` or ``reference`` project of ``case`` into ``dest`` (its py/ folder). Returns dest."""
    spec = str(case[which])
    dest.mkdir(parents=True, exist_ok=True)
    if spec == "empty":
        return dest
    kind, _, value = spec.partition(":")
    names = templates(skills)
    base = value if kind == "template" else case.get("base")
    if kind not in ("template", "overlay") or base not in names:
        raise ValueError(f"{case['id']}: bad {which} {spec!r} (base {base!r})")
    shutil.copytree(names[base] / "prep", dest / "prep", dirs_exist_ok=True)
    if (names[base] / "post").is_dir():  # combinations + code checks, generated by tools/gen_post.py
        shutil.copytree(names[base] / "post", dest / "post", dirs_exist_ok=True)
    if kind == "overlay":
        overlay = case["_dir"] / value
        for path in sorted(p for p in overlay.rglob("*") if p.is_file()):
            target = dest / path.relative_to(overlay)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, target)
        deletions = case["_dir"] / f"{value}.delete"
        for line in deletions.read_text(encoding="utf-8").splitlines() if deletions.is_file() else []:
            if line.strip():
                (dest / line.strip()).unlink()
    return dest
